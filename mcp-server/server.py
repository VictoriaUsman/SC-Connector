# ── Helpers ─────────────────────────────────────────────────────────────


def _err(exc: ApiError) -> dict:
    return {"error": True, "code": exc.code, "message": str(exc)}


# ── Read-only tools ─────────────────────────────────────────────────────


@mcp.tool(annotations={"readOnlyHint": True})
async def list_clients(active_only: bool = False) -> list[dict] | dict:
    """List all configured Amazon seller clients.

    Each client represents an Amazon seller account with SP API and/or
    Ads API credentials. Returns id, name, marketplaces, and connection
    status. Use this to discover valid client_ids.
    """
    try:
        return await api.list_clients(active=active_only)
    except ApiError as e:
        return _err(e)


