@mcp.tool(annotations={"readOnlyHint": False, "idempotentHint": False, "openWorldHint": True})
async def request_report(
    client_id: str,
    api_source: str,
    marketplace: str,
    report_types: list[str],
    start_date: str,
    end_date: str,
    folder_name: str = "",
    subfolder_strategy: str = "date",
) -> dict:
    """Request an on-demand report download for a specific date range.

    Each report_type gets its own workflow. Date range cannot exceed 60 days.
    Use list_report_types to find valid IDs, list_clients for client IDs.

    Args:
        client_id: Amazon seller client ID.
        api_source: 'sp_api', 'ads_api', or 'both'.
        marketplace: Single marketplace code (e.g. 'US').
        report_types: Report type IDs.
        start_date: YYYY-MM-DD.
        end_date: YYYY-MM-DD.
        folder_name: Custom Drive folder prefix.
        subfolder_strategy: 'date' or 'none'.
    """
    try:
        return await api.request_on_demand({
            "client_id": client_id,
            "api_source": api_source,
            "marketplace": marketplace,
            "report_types": report_types,
            "start_date": start_date,
            "end_date": end_date,
            "folder_name": folder_name,
            "subfolder_strategy": subfolder_strategy,
        })
    except ApiError as e:
        return _err(e)


