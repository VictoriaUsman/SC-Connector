"""Kalilos MCP Server — agentic interface to the Amazon Reports Connector.

Exposes 15 tools for managing report schedules, triggering on-demand reports,
monitoring job status, and discovering Ads API profiles. Works across Cursor,
Claude Desktop, Claude.ai, Claude Code, and the Anthropic API.

Run locally:
    python server.py                     # HTTP on :8080
    MCP_TRANSPORT=stdio python server.py # stdio for Cursor/Claude Code

Deploy:
    Cloud Run via Dockerfile (uvicorn + ASGI)
"""

from __future__ import annotations

import os
from contextlib import asynccontextmanager

from fastmcp import FastMCP
from starlette.requests import Request
from starlette.responses import JSONResponse

from api_client import ApiError, KalilosApiClient
from auth import create_auth_provider

# ── HTTP client (shared across all tool calls) ──────────────────────────

api = KalilosApiClient()


@asynccontextmanager
async def lifespan(app: FastMCP):
    yield
    await api.close()


# ── Server ──────────────────────────────────────────────────────────────

mcp = FastMCP(
    "kalilos",
    instructions=(
        "Kalilos Amazon Reports Connector. Manage Amazon SP API and Ads API "
        "report schedules, trigger on-demand report downloads, and monitor "
        "job status. Reports are stored in Google Drive.\n\n"
        "Marketplaces: US, CA, MX, UK, DE, FR, IT, ES, AU.\n"
        "API sources: sp_api, ads_api, or both.\n"
        "Timeframe strategies: yesterday, today, last_n_days, rolling_window, "
        "last_calendar_week, last_calendar_month.\n\n"
        "Typical workflow: list_clients -> list_report_types -> "
        "create_schedule or request_report -> list_jobs to monitor."
    ),
    auth=create_auth_provider(),
    lifespan=lifespan,
)


# ── Health check (custom route, no auth) ────────────────────────────────


@mcp.custom_route("/health", methods=["GET"])
async def health(request: Request) -> JSONResponse:
    return JSONResponse({"status": "ok", "service": "kalilos-mcp"})


